import { useState } from 'react';
import { api } from '../api';

export default function Ask() {
  const [question, setQuestion] = useState('');
  const [result, setResult] = useState(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);

  const submit = async (e) => {
    e.preventDefault();
    setError(''); setResult(null); setBusy(true);
    try {
      setResult(await api('/faqs/ask', { method: 'POST', body: { question } }));
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <div>
      <h2>Ask a question</h2>
      <form className="row" onSubmit={submit}>
        <input value={question} onChange={(e) => setQuestion(e.target.value)} placeholder="Type your question..." required minLength={3} />
        <button className="btn" disabled={busy}>{busy ? 'Thinking...' : 'Ask'}</button>
      </form>
      {error && <p className="error">{error}</p>}
      {result && (
        <div className="card">
          <span className={`badge ${result.source}`}>
            {result.source === 'faq' ? 'From saved FAQ' : 'Generated by AI (Gemini) and saved'}
          </span>
          <p className="answer">{result.answer}</p>
        </div>
      )}
    </div>
  );
}
